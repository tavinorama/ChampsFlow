-- source_provenance (#159A, from the Signal-Engine spec's golden rule #2):
-- every external signal we collect must answer, in one place, "under which
-- terms, under which legal basis, and for how long?".
--
-- Before this table those answers lived in code comments (reddit-signal.ts
-- says "public SERP results, NOT the Reddit Data API") — true, but invisible
-- to the ROPA (#142), to DPA reviews (#143), and to the enterprise DPO who
-- gatekeeps agency deals. A registry the compliance artifacts can JOIN against
-- is what turns "we behave well" into "we can show it".
--
-- Reference data, not per-tenant data: no RLS, readable by the app role.
-- Rows are UPDATED when a ToS version or retention decision changes — the
-- registry describes the CURRENT collection contract; history lives in git.

CREATE TABLE IF NOT EXISTS source_registry (
  id               TEXT PRIMARY KEY,          -- stable slug referenced by signal rows
  source_type      TEXT NOT NULL,             -- llm_answer | serp | social_public | web_crawl | first_party | places
  platform         TEXT NOT NULL,             -- human-readable origin
  collection_method TEXT NOT NULL,            -- how we obtain it (api_query, direct_fetch, user_input)
  -- ToS identity under which collection happens. Not a marketing string: when
  -- a provider revises terms, this value changes in a reviewed migration.
  tos_version      TEXT NOT NULL,
  -- GDPR Art. 6 / LGPD Art. 7 basis for the collection.
  legal_basis      TEXT NOT NULL
                     CHECK (legal_basis IN ('legitimate_interest', 'contract', 'consent')),
  -- Days raw collected text is retained before purge. NULL = kept for the
  -- life of the account (first-party data under contract). 0 = never stored
  -- raw (aggregates only).
  retention_days   INTEGER,
  notes            TEXT NOT NULL DEFAULT ''
);

