-- The FK from collected signals to their provenance. citation_check is the
-- per-probe evidence row — the one table where collected external text lands.
-- (Offsite/Reddit aggregates ride inside geo_score.provider_breakdown JSON and
-- carry no raw text; their provenance is the registry rows themselves.)
-- Nullable: rows predating this migration stay NULL rather than being
-- back-stamped with a provenance we did not record at collection time.
ALTER TABLE citation_check
  ADD COLUMN IF NOT EXISTS source_id TEXT REFERENCES source_registry (id);
